    <p>
        My research will focus in the broader context of quantum computing. Some of the work started during my Post-doctoral research in Simula-UiB. I started working with problems related to quantum-safe cryptography, in particular, the lattice approach. Lattice-based cryptography is a possible alternative to RSA. Some lattice-based cryptosystems seem to be safe under quantum-algorithmic attacks and the computational cost of these systems is not too far off from that of RSA-based cryptosystems. 
    </p>
    <p>
        Apart from above work, I would like to focus on quantum circuits, in particular understanding the classification of unitary matrices. In general, the decomposition of a unitary matrix into universal set of base unitary matrices is exponential in the number of qubits. The aim of this approach is to classify matrices that would lead to polynomial-size decomposition. 
    </p>
    <p>
        Another interesting area of work is understanding entanglement as a resource. In quantum communication algorithms such as quantum teleportation, 2 classical bits and an entangled pair is needed to complete the task. I would like to understand such class of communication protocols and their lower limit of communition resources.
    </p>
    <p>
        To further the research in quantum computing, it is essential that a research group is constructed here in India. My motivation to work in this field originated back in 2005 when I was a masters student in IIT Kanpur. It is high-time now that India should have many teams working and collaborating in this field.
    </p>
